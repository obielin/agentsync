"""Aider must read the rules as a file, rather than as YAML comments."""

import json

import pytest

from agentsync import AgentSyncer
from agentsync.config import LOCK_FILE, write_config, write_rules
from agentsync.tools import get_tool

RULES = "# Project rules\n- Use tabs\n"


@pytest.fixture
def project(tmp_path):
    write_config(tmp_path, tools=["aider"])
    write_rules(RULES, root=tmp_path)
    return tmp_path


@pytest.mark.parametrize(
    "rules",
    [RULES, "# Rules: café\nread: [do-not-load-this.yaml]\n- Keep literal: # punctuation\n"],
)
def test_sync_creates_config_and_readable_conventions(project, rules):
    write_rules(rules, root=project)
    report = AgentSyncer(root=project).sync()
    assert report.created == 2
    config = (project / ".aider.conf.yml").read_text(encoding="utf-8")
    assert [line for line in config.splitlines() if line and not line.startswith("#")] == [
        "read: CONVENTIONS.md"
    ]
    conventions = (project / "CONVENTIONS.md").read_text(encoding="utf-8")
    assert rules in conventions
    assert "Generated by agentsync" in config
    assert "Generated by agentsync" in conventions


def test_dry_run_reports_both_outputs_without_writing(project):
    report = AgentSyncer(root=project).sync(dry_run=True)
    assert report.created == 2
    assert {result.output_path for result in report.results} == {
        ".aider.conf.yml",
        "CONVENTIONS.md",
    }
    assert not (project / ".aider.conf.yml").exists()
    assert not (project / "CONVENTIONS.md").exists()
    assert not (project / LOCK_FILE).exists()
    assert not (project / ".gitignore").exists()


def test_subsequent_sync_updates_only_conventions(project):
    syncer = AgentSyncer(root=project)
    syncer.sync()
    assert syncer.sync().unchanged == 2
    config_before = (project / ".aider.conf.yml").read_bytes()
    write_rules("# Updated rules\n- Use spaces\n", root=project)
    report = syncer.sync()
    assert report.updated == 1
    assert report.unchanged == 1
    assert (project / ".aider.conf.yml").read_bytes() == config_before
    assert "Use spaces" in (project / "CONVENTIONS.md").read_text(encoding="utf-8")


def test_aider_outputs_are_recognised_and_tracked(project):
    syncer = AgentSyncer(root=project)
    syncer.sync()
    assert syncer.detect_unmanaged() == []
    statuses = syncer.status()
    assert len(statuses) == 2
    assert all(status["status"] == "ok" for status in statuses)
    lock = json.loads((project / LOCK_FILE).read_text(encoding="utf-8"))
    assert set(lock["tools"]) == {".aider.conf.yml", "CONVENTIONS.md"}
    ignored = (project / ".gitignore").read_text(encoding="utf-8").splitlines()
    assert ".aider.conf.yml" in ignored
    assert "CONVENTIONS.md" in ignored


def test_generate_without_output_path_still_returns_config(project):
    AgentSyncer(root=project).sync()
    assert get_tool("aider").generate(RULES) == (project / ".aider.conf.yml").read_text(
        encoding="utf-8"
    )


def test_sync_updates_existing_generated_ignore_block(project):
    ignore = project / ".gitignore"
    ignore.write_bytes(
        b"# agentsync generated files\r\n.aider.conf.yml\r\n\r\n# User patterns\r\nbuild/\r\n"
    )
    syncer = AgentSyncer(root=project)

    assert syncer.sync().errors == 0
    expected = (
        b"# agentsync generated files\r\nCONVENTIONS.md\r\n.aider.conf.yml\r\n"
        b"\r\n# User patterns\r\nbuild/\r\n"
    )
    assert ignore.read_bytes() == expected
    assert syncer.sync().errors == 0
    assert ignore.read_bytes() == expected
