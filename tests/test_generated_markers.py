"""Generated rule files must be distinguishable from handwritten files."""

import argparse

import pytest

from agentsync import ALL_TOOLS, AgentSyncer
from agentsync.cli import cmd_adopt
from agentsync.config import RULES_FILE, write_config, write_rules
from agentsync.tools import DEFAULT_TOOLS

RULES = "# Claude project rules\n- Use tabs\n"


@pytest.mark.parametrize("tool_id", ALL_TOOLS)
def test_every_generator_marks_its_output(tool_id):
    generated = ALL_TOOLS[tool_id].generate(RULES)
    assert "Generated by agentsync" in generated


def test_default_sync_has_no_unmanaged_files(tmp_path):
    write_config(tmp_path, tools=DEFAULT_TOOLS)
    write_rules(RULES, root=tmp_path)
    syncer = AgentSyncer(root=tmp_path)
    syncer.sync()
    assert syncer.detect_unmanaged() == []


def test_adopt_ignores_generated_files(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    write_config(tmp_path, tools=DEFAULT_TOOLS)
    write_rules(RULES, root=tmp_path)
    AgentSyncer(root=tmp_path).sync()
    canonical_before = (tmp_path / RULES_FILE).read_bytes()

    assert cmd_adopt(argparse.Namespace()) == 0
    assert "No unmanaged rule files found." in capsys.readouterr().out
    assert (tmp_path / RULES_FILE).read_bytes() == canonical_before


def test_adopt_lists_shared_output_path_once(tmp_path, monkeypatch, capsys):
    monkeypatch.chdir(tmp_path)
    write_config(tmp_path)
    write_rules(RULES, root=tmp_path)
    (tmp_path / "AGENTS.md").write_text("# Short handwritten rules\n", encoding="utf-8")
    chosen = "# Longer handwritten rules\n- Follow all of the team's conventions\n"
    (tmp_path / "CLAUDE.md").write_text(chosen, encoding="utf-8")

    assert cmd_adopt(argparse.Namespace()) == 0
    assert capsys.readouterr().out.count("AGENTS.md") == 1
    assert (tmp_path / RULES_FILE).read_text(encoding="utf-8") == chosen


def test_detect_unmanaged_lists_shared_output_path_once(tmp_path):
    (tmp_path / "AGENTS.md").write_text("# Handwritten rules\n", encoding="utf-8")
    assert AgentSyncer(root=tmp_path).detect_unmanaged() == ["AGENTS.md"]
